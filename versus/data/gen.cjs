#!/usr/bin/env node
// Generates data.ts from the .json files in this directory.
//
// Why a generator: MAM does not compile arbitrary .json into the web bundle,
// and fetching six files at runtime would make every consumer handle loading
// and failure states for 26 KB of static text. So the JSON stays the source of
// truth for humans and the generator embeds it into a TS module that bundles.
//
// Why the escaping: MAM's TS dependor ( mol/build/build.node.ts ) scans the
// whole source text for `$name` tokens and treats them as module deps. The
// title "$mol" would resolve to the entire mol/ package. So every `$` is
// emitted as $ — invisible to the dependor, identical string at runtime.
// Same trick as content/gen.cjs.
//
// Re-run after editing any .json here:  node bog/smalljs/versus/data/gen.cjs

const fs = require( 'fs' )
const path = require( 'path' )

const root = __dirname

const registry = JSON.parse( fs.readFileSync( path.join( root, 'registry.json' ), 'utf8' ) )

const frameworks = fs.readdirSync( root )
	.filter( name => name.endsWith( '.json' ) && name !== 'registry.json' )
	.map( name => JSON.parse( fs.readFileSync( path.join( root, name ), 'utf8' ) ) )
	// Alphabetical, ignoring sigils — otherwise "$mol" sorts first and an
	// impartial list opens with the framework this site is about.
	.sort( ( a, b ) => a.title.replace( /^\W+/, '' ).localeCompare( b.title.replace( /^\W+/, '' ) ) )

for( const fw of frameworks ) {
	for( const [ id, rec ] of Object.entries( fw.metrics ) ) {
		if( !registry[ id ] ) throw new Error( `${ fw.id }: metric "${ id }" is not in registry.json` )
		for( const field of [ 'value', 'source', 'measured_at' ] ) {
			if( rec[ field ] === undefined || rec[ field ] === null ) {
				throw new Error( `${ fw.id }.${ id }: missing ${ field }` )
			}
		}
	}
}

/** JSON literal with every `$` neutralized for the dependor. */
const lit = value => JSON.stringify( value ).replace( /\$/g, '\\u0024' )

const out = []
const put = ( indent, line ) => out.push( '\t'.repeat( indent ) + line )

put( 0, 'namespace $ {' )
put( 0, '' )
put( 1, '/**' )
put( 1, ' * Static comparison data for the versus section. GENERATED by' )
put( 1, ' * versus/data/gen.cjs — do not edit by hand; edit the .json files next to it' )
put( 1, ' * and re-run the generator.' )
put( 1, ' *' )
put( 1, ' * Every value carries the source it came from and the date it was taken.' )
put( 1, ' * A metric nobody could measure is absent — never null, never 0.' )
put( 1, ' */' )
put( 1, 'export type $bog_smalljs_versus_data_value = {' )
put( 2, 'value: number | boolean' )
put( 2, '/** URL the number can be checked against. */' )
put( 2, 'source: string' )
put( 2, '/** ISO date the measurement was taken. */' )
put( 2, 'measured_at: string' )
put( 2, '/** Optional deeper link: the exact run, package page or tooling. */' )
put( 2, 'method?: string' )
put( 1, '}' )
put( 0, '' )
put( 1, 'export type $bog_smalljs_versus_data_framework = {' )
put( 2, 'id: string' )
put( 2, 'title: string' )
put( 2, '/** Year the canonical repository was created. */' )
put( 2, 'since?: number' )
put( 2, 'since_source?: string' )
put( 2, '/** True only where a live crash-test runner exists. */' )
put( 2, 'runner?: boolean' )
put( 2, 'metrics: Readonly< Record< string, $bog_smalljs_versus_data_value > >' )
put( 1, '}' )
put( 0, '' )
put( 1, 'export type $bog_smalljs_versus_data_metric = {' )
put( 2, 'category: string' )
put( 2, 'title: string' )
put( 2, 'unit: string' )
put( 2, "better: 'lower' | 'higher' | 'boolean'" )
put( 2, '/** Plain sentence saying why the number matters. */' )
put( 2, 'human: string' )
put( 2, '/** How the number is obtained, same for every framework. */' )
put( 2, 'method?: string' )
put( 1, '}' )
put( 0, '' )
put( 1, 'export class $bog_smalljs_versus_data extends $mol_object2 {' )
put( 0, '' )
put( 2, '/** Metric descriptions, keyed by metric id. */' )
put( 2, 'static registry(): Readonly< Record< string, $bog_smalljs_versus_data_metric > > {' )
put( 3, 'return {' )
for( const [ id, meta ] of Object.entries( registry ) ) {
	put( 4, `${ lit( id ) }: ${ lit( meta ) },` )
}
put( 3, '}' )
put( 2, '}' )
put( 0, '' )
put( 2, 'static metric( id: string ): $bog_smalljs_versus_data_metric | null {' )
put( 3, 'return this.registry()[ id ] ?? null' )
put( 2, '}' )
put( 0, '' )
put( 2, '/** Every framework, keyed by id. */' )
put( 2, 'static items(): Readonly< Record< string, $bog_smalljs_versus_data_framework > > {' )
put( 3, 'return {' )
for( const fw of frameworks ) {
	put( 4, `${ lit( fw.id ) }: ${ lit( fw ) },` )
}
put( 3, '}' )
put( 2, '}' )
put( 0, '' )
put( 2, '/** Every framework, sorted by title. Never throws, never empty-checks. */' )
put( 2, 'static list(): readonly $bog_smalljs_versus_data_framework[] {' )
put( 3, 'return [' )
for( const fw of frameworks ) put( 4, `${ lit( fw.id ) },` )
put( 3, '].map( id => this.items()[ id ] )' )
put( 2, '}' )
put( 0, '' )
put( 2, 'static item( id: string ): $bog_smalljs_versus_data_framework | null {' )
put( 3, 'return this.items()[ id ] ?? null' )
put( 2, '}' )
put( 0, '' )
put( 2, '/** One measurement, or null when this framework has no data for it. */' )
put( 2, 'static value( framework: string, metric: string ): $bog_smalljs_versus_data_value | null {' )
put( 3, 'return this.item( framework )?.metrics[ metric ] ?? null' )
put( 2, '}' )
put( 0, '' )
put( 1, '}' )
put( 0, '' )
put( 0, '}' )
put( 0, '' )

fs.writeFileSync( path.join( root, 'data.ts' ), out.join( '\n' ) )

console.log(
	'data.ts:', frameworks.length, 'frameworks,',
	Object.keys( registry ).length, 'metrics,',
	frameworks.reduce( ( n, fw ) => n + Object.keys( fw.metrics ).length, 0 ), 'values'
)
